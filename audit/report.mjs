// audit/report.mjs — the artefact a human reads, and the one a diff reads.
//
// Markdown is grouped by severity, because the first question is always "what is
// broken", not "which page has the most findings". Per-page detail follows for
// the pages that have something to say.

import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const ORDER = ['blocker', 'major', 'minor', 'info'];
const LABEL = { blocker: 'Blockers', major: 'Major', minor: 'Minor', info: 'Info' };

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');

export function buildJson({ meta, scoring, findings }) {
  return {
    generatedAt: new Date().toISOString(),
    ...meta,
    score: scoring.site.score,
    totals: scoring.site.totals,
    byGroup: scoring.byGroup,
    findings: findings.map((f) => ({
      id: f.id,
      severity: f.severity,
      group: f.group,
      page: f.page,
      message: f.message,
      fix: f.fix,
      evidence: f.evidence || null,
    })),
  };
}

export function buildMarkdown({ meta, scoring, findings, ruleCount }) {
  const date = new Date().toISOString().slice(0, 10);
  const lines = [];

  lines.push(`# Sitemap audit — ${date}`);
  lines.push('');
  lines.push(`**Target:** ${meta.target}  ·  **URLs:** ${meta.pageCount}  ·  **Crawl:** ${meta.elapsedMs} ms  ·  **Rules:** ${ruleCount}  ·  **Score:** ${scoring.site.score}/100`);
  lines.push('');
  lines.push('| Severity | Count |');
  lines.push('|---|---|');
  for (const s of ORDER) lines.push(`| ${LABEL[s]} | ${scoring.site.totals[s] || 0} |`);
  lines.push('');

  lines.push('| Section | Pages | Score | Blockers | Major | Minor |');
  lines.push('|---|---|---|---|---|---|');
  for (const [g, v] of Object.entries(scoring.byGroup)) {
    lines.push(`| ${g} | ${v.pages} | ${v.score} | ${v.blocker} | ${v.major} | ${v.minor} |`);
  }
  lines.push('');

  if (!findings.length) {
    lines.push('No findings. Every URL in the sitemap passed every rule.');
    lines.push('');
  }

  for (const sev of ORDER) {
    const group = findings.filter((f) => f.severity === sev);
    if (!group.length) continue;
    lines.push(`## ${LABEL[sev]} (${group.length})`);
    lines.push('');
    for (const f of group) {
      lines.push(`### \`${f.id}\` — ${esc(f.page)}`);
      lines.push('');
      lines.push(`**Finding:** ${esc(f.message)}`);
      lines.push('');
      lines.push(`**Fix:** ${esc(f.fix)}`);
      if (f.evidence) {
        const ev = JSON.stringify(f.evidence);
        lines.push('');
        lines.push(`<details><summary>Evidence</summary>`);
        lines.push('');
        lines.push('```json');
        lines.push(ev.length > 1200 ? ev.slice(0, 1200) + '…' : ev);
        lines.push('```');
        lines.push('');
        lines.push('</details>');
      }
      lines.push('');
    }
  }

  const dirty = scoring.pages.filter((p) => p.findings.length).sort((a, b) => a.score - b.score);
  if (dirty.length) {
    lines.push(`## Pages with findings (${dirty.length} of ${scoring.pages.length})`);
    lines.push('');
    lines.push('| Page | Score | Blk | Maj | Min | Rules |');
    lines.push('|---|---|---|---|---|---|');
    for (const p of dirty) {
      const ids = [...new Set(p.findings.map((f) => f.id))].join(', ');
      lines.push(`| ${esc(p.path)} | ${p.score} | ${p.counts.blocker} | ${p.counts.major} | ${p.counts.minor} | ${esc(ids)} |`);
    }
    lines.push('');
  }

  const clean = scoring.pages.filter((p) => !p.findings.length);
  if (clean.length) {
    lines.push(`## Clean pages (${clean.length})`);
    lines.push('');
    lines.push(clean.map((p) => p.path).join(' · '));
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('Generated by `npm run audit`. Thresholds live in `audit/rules/catalog.json`;');
  lines.push('the rule set and its fixes are in `audit/rules/`.');
  lines.push('');
  return lines.join('\n');
}

export function consoleSummary({ scoring, findings }) {
  const out = [];
  out.push('');
  out.push(`score ${scoring.site.score}/100 over ${scoring.pages.length} pages`);
  out.push(`blockers ${scoring.site.totals.blocker}  major ${scoring.site.totals.major}  minor ${scoring.site.totals.minor}  info ${scoring.site.totals.info}`);
  const top = findings.filter((f) => f.severity === 'blocker' || f.severity === 'major').slice(0, 12);
  if (top.length) {
    out.push('');
    for (const f of top) out.push(`  ${f.severity === 'blocker' ? 'BLOCK' : 'MAJOR'}  ${f.page}  ${f.id}  ${f.message}`);
    if (findings.filter((f) => f.severity === 'blocker' || f.severity === 'major').length > top.length) out.push('  …');
  }
  return out.join('\n');
}

export async function writeReports({ dir, target = 'live', markdown, json }) {
  await mkdir(dir, { recursive: true });
  const date = new Date().toISOString().slice(0, 10);
  // The live report is the canonical one and keeps the plain name. A dist run
  // writes alongside it rather than overwriting it: an offline build is evidence
  // about the source, not about what visitors were served.
  const suffix = target === 'live' ? '' : `-${target}`;
  const reportPath = path.join(dir, `report-${date}${suffix}.md`);
  const latestPath = path.join(dir, `latest${suffix}.json`);
  await writeFile(reportPath, markdown);
  await writeFile(latestPath, JSON.stringify(json, null, 2) + '\n');
  return { reportPath, latestPath };
}
